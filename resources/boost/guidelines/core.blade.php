## AgenticGraph Vector

- AgenticGraph Vector stores documents in pgvector, embeds text, and returns similar hits through the `Vector` and `Embeddings` facades. It retrieves; prompting and generation are your code.
- IMPORTANT: Activate `agenticgraph-vector` when configuring vector stores, creating collections, ingesting documents, searching, tuning scores, building RAG nodes, checking store capabilities, reading vector events or spans, or handling vector exceptions.
